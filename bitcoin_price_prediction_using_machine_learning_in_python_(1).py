def adapt_model(existing_df: pd.DataFrame, new_rows: pd.DataFrame) -> pd.DataFrame:
    """Append new candles, re-preprocess, return updated DataFrame."""
    combined = pd.concat([existing_df[["close", "volume"]], new_rows[["close", "volume"]]])
    combined = combined[~combined.index.duplicated(keep="last")]
    updated  = preprocess(combined)
    print(f"[Adapt] Dataset updated: {len(existing_df)} → {len(updated)} rows.")
    return updated


