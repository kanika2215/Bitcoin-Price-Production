def fetch_bitcoin_data(days: int = 90, source: str = "coingecko") -> pd.DataFrame:
    if source == "coingecko":
        try:
            url = (
                "https://api.coingecko.com/api/v3/coins/bitcoin/market_chart"
                f"?vs_currency=usd&days={days}&interval=daily"
            )
            resp = requests.get(url, timeout=10)
            resp.raise_for_status()
            raw = resp.json()

            prices  = raw["prices"]
            volumes = raw["total_volumes"]

            df = pd.DataFrame(prices, columns=["timestamp", "close"])
            df["volume"] = [v[1] for v in volumes]
            df["date"]   = pd.to_datetime(df["timestamp"], unit="ms").dt.normalize()
            df = df.drop(columns=["timestamp"]).set_index("date")
            print(f"[CoinGecko] Fetched {len(df)} days of BTC data.")
            return df

        except Exception as e:
            print(f"[CoinGecko] Failed: {e}. Trying yfinance...")

    try:
        import yfinance as yf
        ticker = yf.Ticker("BTC-USD")
        df = ticker.history(period=f"{days}d")[["Close", "Volume"]]
        df.columns = ["close", "volume"]
        df.index.name = "date"
        df.index = df.index.normalize()
        print(f"[yfinance] Fetched {len(df)} days of BTC data.")
        return df

    except Exception as e:
        print(f"[yfinance] Failed: {e}. Using synthetic data.")
        return generate_synthetic_data(days)


def generate_synthetic_data(days: int = 90) -> pd.DataFrame:
    np.random.seed(42)
    dates = pd.date_range(end=datetime.today().date(), periods=days + 1, freq="D")
    price = 62_000.0
    prices, volumes = [], []
    for _ in range(len(dates)):
        price *= 1 + np.random.normal(0.001, 0.03)
        price  = max(15_000, min(150_000, price))
        prices.append(round(price, 2))
        volumes.append(abs(np.random.normal(25e9, 8e9)))
    df = pd.DataFrame({"close": prices, "volume": volumes}, index=dates)
    df.index.name = "date"
    print(f"[Synthetic] Generated {len(df)} days of BTC data.")
    return df


def preprocess(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy().dropna(subset=["close"])

    # Remove outliers beyond 5 × IQR
    q1, q3 = df["close"].quantile(0.25), df["close"].quantile(0.75)
    iqr = q3 - q1
    df  = df[(df["close"] >= q1 - 5 * iqr) & (df["close"] <= q3 + 5 * iqr)]

    df = df.sort_index()
    df["day_index"] = np.arange(len(df))

    # Log returns
    df["returns"] = np.log(df["close"] / df["close"].shift(1))

    # Moving averages
    df["ma_7"]  = df["close"].rolling(7).mean()
    df["ma_21"] = df["close"].rolling(21).mean()

    # Rolling volatility
    df["vol_7"] = df["returns"].rolling(7).std()

    # RSI-14
    delta = df["close"].diff()
    gain  = delta.clip(lower=0).rolling(14).mean()
    loss  = (-delta.clip(upper=0)).rolling(14).mean()
    rs    = gain / loss.replace(0, np.nan)
    df["rsi_14"] = 100 - (100 / (1 + rs))

    # Normalised price
    scaler = MinMaxScaler()
    df["price_norm"] = scaler.fit_transform(df[["close"]])

    print(f"[Preprocess] {len(df)} rows after cleaning. Features: {list(df.columns)}")
    return df


class ModelResult:
    def __init__(self, name, fitted, forecast, rmse, mae, r2):
        self.name     = name
        self.fitted   = fitted
        self.forecast = forecast
        self.rmse     = rmse
        self.mae      = mae
        self.r2       = r2

    def __repr__(self):
        return (f"<{self.name}  RMSE=${self.rmse:,.0f}  "
                f"MAE=${self.mae:,.0f}  R²={self.r2:.4f}>")


def train_linear(X_train, y_train, X_future):
    model = LinearRegression()
    model.fit(X_train, y_train)
    return model.predict(X_train), model.predict(X_future)


def train_polynomial(X_train, y_train, X_future, degree=3):
    model = make_pipeline(PolynomialFeatures(degree), LinearRegression())
    model.fit(X_train, y_train)
    return model.predict(X_train), model.predict(X_future)


def train_moving_average(prices: np.ndarray, forecast_days: int, window=7):
    fitted = pd.Series(prices).rolling(window).mean().values
    series = list(prices[-window:])
    future = []
    for _ in range(forecast_days):
        nxt = np.mean(series[-window:])
        future.append(nxt)
        series.append(nxt)
    return fitted, np.array(future)


def evaluate(y_true, y_pred) -> dict:
    mask = ~np.isnan(y_pred)
    yt, yp = y_true[mask], y_pred[mask]
    return {
        "rmse": np.sqrt(mean_squared_error(yt, yp)),
        "mae":  mean_absolute_error(yt, yp),
        "r2":   r2_score(yt, yp),
    }


def run_all_models(df: pd.DataFrame, forecast_days: int = 30) -> dict:
    prices   = df["close"].values
    X        = df[["day_index"]].values
    last_idx = int(df["day_index"].iloc[-1])
    X_future = np.arange(last_idx + 1, last_idx + 1 + forecast_days).reshape(-1, 1)

    results = {}

    fitted_lr, forecast_lr = train_linear(X, prices, X_future)
    m = evaluate(prices, fitted_lr)
    results["Linear Regression"] = ModelResult(
        "Linear Regression", fitted_lr, forecast_lr, m["rmse"], m["mae"], m["r2"]
    )

    fitted_poly, forecast_poly = train_polynomial(X, prices, X_future, degree=3)
    m = evaluate(prices, fitted_poly)
    results["Polynomial Regression"] = ModelResult(
        "Polynomial Regression", fitted_poly, forecast_poly, m["rmse"], m["mae"], m["r2"]
    )

    fitted_ma, forecast_ma = train_moving_average(prices, forecast_days, window=7)
    ma_valid = ~np.isnan(fitted_ma)
    m = evaluate(prices[ma_valid], fitted_ma[ma_valid])
    results["Moving Average"] = ModelResult(
        "Moving Average", fitted_ma, forecast_ma, m["rmse"], m["mae"], m["r2"]
    )

    for name, res in results.items():
        print(f"[Model] {res}")

    return results

